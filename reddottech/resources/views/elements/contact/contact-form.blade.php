                    <script>
                        document.addEventListener('DOMContentLoaded', function () {
                            const radios = document.querySelectorAll('input[name="subject"]');
                            if (!radios.length) return;

                            function updateSubjectText() {
                                radios.forEach(radio => {
                                    const label = radio.closest('label');
                                    if (!label) return;
                                    const textEl = label.querySelector('span');
                                    if (!textEl) return;

                                    if (radio.checked) {
                                        textEl.classList.remove('text-gray-700');
                                        textEl.classList.add('text-primary');
                                    } else {
                                        textEl.classList.remove('text-primary');
                                        // ensure a reasonable fallback color class
                                        if (!textEl.classList.contains('text-gray-700')) {
                                            textEl.classList.add('text-gray-700');
                                        }
                                    }
                                });
                            }

                            radios.forEach(r => r.addEventListener('change', updateSubjectText));
                            // initial pass in case an option is pre-selected (old value)
                            updateSubjectText();
                        });
